import { Router } from "express";
import prisma from "../config/prisma.js";
import {
  createDocumentSchema,
  updateDocumentSchema,
} from "../validators/document.validator.js";
import fs from "node:fs/promises";
import { fileTypeFromFile } from "file-type";

import { documentStorageDirectory, uploadPdf } from "../config/multer.js";
import path from "node:path";

const router = Router();

// GET /api/documents
// Retrieve all documents.
router.get("/", async (_req, res, next) => {
  try {
    const documents = await prisma.document.findMany({
      orderBy: {
        createdAt: "desc",
      },
    });

    res.status(200).json({
      success: true,
      data: documents,
    });
  } catch (error) {
    next(error);
  }
});

router.post(
  "/upload",
  (req, res, next) => {
    uploadPdf.single("file")(req, res, (error) => {
      if (error) {
        next(error);
        return;
      }

      next();
    });
  },
  async (req, res, next) => {
    let savedFilePath: string | undefined;

    try {
      if (!req.file) {
        res.status(400).json({
          success: false,
          message: "Please upload a PDF file using the 'file' field",
        });
        return;
      }

      savedFilePath = req.file.path;

      // Inspect the actual file contents rather than trusting the MIME type.
      const detectedType = await fileTypeFromFile(savedFilePath);

      if (detectedType?.mime !== "application/pdf") {
        await fs.unlink(savedFilePath);
        savedFilePath = undefined;

        res.status(400).json({
          success: false,
          message: "The uploaded file is not a valid PDF",
        });
        return;
      }

      const document = await prisma.document.create({
        data: {
          filename: req.file.originalname,
          storageKey: req.file.filename,
          mimeType: detectedType.mime,
          size: req.file.size,
        },
      });

      res.status(201).json({
        success: true,
        message: "PDF uploaded successfully",
        data: document,
      });
    } catch (error) {
      // If saving the database record fails, remove the uploaded file
      // to avoid leaving an orphaned file on disk.
      if (savedFilePath) {
        try {
          await fs.unlink(savedFilePath);
        } catch (cleanupError) {
          console.error("Failed to clean up uploaded file:", cleanupError);
        }
      }

      next(error);
    }
  },
);

router.get("/:id/text", async (req, res, next) => {
  try {
    const document = await prisma.document.findUnique({
      where: {
        id: req.params.id,
      },
      select: {
        id: true,
        filename: true,
        status: true,
        extractedText: true,
        pageCount: true,
        extractedAt: true,
      },
    });

    if (!document) {
      res.status(404).json({
        success: false,
        message: "Document not found",
      });

      return;
    }

    if (!document.extractedText) {
      res.status(409).json({
        success: false,
        message: "Text has not been extracted yet",
      });

      return;
    }

    res.status(200).json({
      success: true,
      data: document,
    });
  } catch (error) {
    next(error);
  }
});

router.get("/:id/download", async (req, res, next) => {
  try {
    const document = await prisma.document.findUnique({
      where: {
        id: req.params.id,
      },
    });

    if (!document) {
      res.status(404).json({
        success: false,
        message: "Document not found",
      });
      return;
    }

    // storageKey is generated by the server, not supplied by the client.
    const filePath = path.join(documentStorageDirectory, document.storageKey);

    res.download(filePath, document.filename, (error) => {
      if (error && !res.headersSent) {
        next(error);
      }
    });
  } catch (error) {
    next(error);
  }
});

// GET /api/documents/:id
// Retrieve one document.
router.get("/:id", async (req, res, next) => {
  try {
    const document = await prisma.document.findUnique({
      where: {
        id: req.params.id,
      },
    });

    if (!document) {
      res.status(404).json({
        success: false,
        message: "Document not found",
      });
      return;
    }

    res.status(200).json({
      success: true,
      data: document,
    });
  } catch (error) {
    next(error);
  }
});

// POST /api/documents
// Create a document record.
router.post("/", async (req, res, next) => {
  try {
    const validatedData = createDocumentSchema.parse(req.body);

    const document = await prisma.document.create({
      data: {
        filename: validatedData.filename,
      },
    });

    res.status(201).json({
      success: true,
      message: "Document created successfully",
      data: document,
    });
  } catch (error) {
    next(error);
  }
});

// PATCH /api/documents/:id
// Update a document record.
router.patch("/:id", async (req, res, next) => {
  try {
    const validatedData = updateDocumentSchema.parse(req.body);

    const document = await prisma.document.update({
      where: {
        id: req.params.id,
      },
      data: validatedData,
    });

    res.status(200).json({
      success: true,
      message: "Document updated successfully",
      data: document,
    });
  } catch (error) {
    next(error);
  }
});

// DELETE /api/documents/:id
// Delete a document record.
router.delete("/:id", async (req, res, next) => {
  try {
    await prisma.document.delete({
      where: {
        id: req.params.id,
      },
    });
    res.status(200).json({
      success: true,
      message: "Document deleted successfully",
    });
  } catch (error) {
    next(error);
  }
});

export default router;
